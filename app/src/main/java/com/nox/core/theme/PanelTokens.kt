package com.nox.core.theme

import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/**
 * 浮层卡片与统计面板的设计令牌。
 *
 * 为什么单独抽一层：这些卡片有大量**精确的小尺寸**（13sp 标题 / 12sp 正文 /
 * 0.5dp 分隔线 / 14dp 图标），散落在各个 Composable 里手写会立刻失控——
 * 同一个面板里出现 12sp/13sp/15sp 三种正文、0.5dp 和 1dp 两种分隔线，
 * 视觉上就是「拼凑感」的来源。集中在这里之后，调用方只引用名字，改一处全站生效。
 *
 * 与 [Spacing] 的分工：[Spacing] 是全局页面级间距（4/8/12/16/24/32），
 * 本对象是**卡片内部**的紧凑尺寸，两者不可互换使用。
 */
object PanelTokens {

    // ── 浮层卡片 ────────────────────────────────────────────────────────────
    /** 浮层卡片圆角。比页面级 [Radius.lg] 略大，浮层边界更柔和。 */
    val cardCorner = Radius.lg
    /**
     * 卡片内边距：横向 16dp；纵向上下分开取。
     *
     * 浮层高度是被数据行数撑起来的，纵向内边距不能跟着横向放大；
     * 但上下都贴到 14dp 时，顶部大数字与底部按钮会“贴边”，视觉上压抑。
     * 上下各留出一点呼吸空间，多出的高度从压缩区里去省（见 [sliderHeight]）。
     */
    val cardPaddingH = 16.dp
    /**
     * 卡片顶部内边距。
     *
     * 顶部大数字与首行明细离卡片上边缘太近，遮住了上方内容的三成，看着像被截断；
     * 拉开后首行不再贴着边。
     */
    val cardPaddingTop = 40.dp
    /**
     * 卡片底部内边距。
     *
     * 与顶部取齐：顶部 20→40、底部 18→40，合计使卡片总高增加 42dp。
     * 首行与尾行各自离边缘 40dp，上下对称，尾部按钮不再顶到底边。
     */
    val cardPaddingBottom = 40.dp
    /** 卡片宽度区间：窄屏不挤，宽屏也不铺满整行。 */
    val cardMinWidth = 256.dp
    val cardMaxWidth = 328.dp
    /** 浮层与窗口边缘的最小留白。 */
    val popupMargin = 12.dp
    /**
     * 浮层与锚点之间的垂直间隙。
     *
     * 取 0：卡片直接贴着触发它的那一行，中间不留缝。早期是 8dp，后来减到 4dp，
     * 真机上仍然看得出「两块独立的东西」——因为锚点取的是**文字矩形**，文字上下
     * 本就有行高留白（12sp 字配 18sp 行高，上下各约 3dp），叠加 4dp 间距后实际
     * 视觉缝宽达 7dp 以上。归零后由锚点自身的行高留白充当呼吸空间，正好贴合。
     */
    val popupAnchorGap = 0.dp
    /** 浮层投影。 */
    val cardShadowRadius = 16.dp
    const val cardShadowAlpha = 0.12f
    /** 浮层描边宽度，比常规边框更细，只用来看清边界。 */
    val cardBorderWidth = 0.5.dp

    // ── 分组标题 ────────────────────────────────────────────────────────────
    /** 分组图标边长。比页面级图标小，避免在紧凑卡片里显得笨重。 */
    val sectionIconSize = 14.dp
    /** 图标与标题之间的间距。 */
    val sectionIconGap = 6.dp
    /** 分组标题字号 / 行高。 */
    val sectionTitleSize = 13.sp
    val sectionTitleLine = 18.sp
    /** 分组标题字重：Medium，比正文略重但不至于抢视线。 */
    val sectionTitleWeight = FontWeight.Medium
    /** 标题右侧补充信息：与标题同字号，数字用等宽。 */
    val sectionTrailingSize = 13.sp
    /** 标题与右侧补充信息之间的最小间距。 */
    val sectionTrailingGap = 16.dp

    // ── 分隔线 ──────────────────────────────────────────────────────────────
    /** 分隔线粗细。0.5dp 在 2x 屏会被抗锯齿抹成半透明而看不见，
     *  0.75dp 在 2x/3x 上都稳定落在 1~2 个物理像素，既细又可见。 */
    val dividerHeight = 0.75.dp
    /** 分隔线上下留白：上紧下松，让下一组内容与标题的关系更近。 */
    val dividerPadTop = 8.dp
    val dividerPadBottom = 10.dp
    /** 分隔线颜色透明度：过重会割裂卡片，过淡看不出分组。 */
    const val dividerAlpha = 0.7f

    // ── 键值行 ──────────────────────────────────────────────────────────────
    /** 键值行标签字号 / 行高。与分组标题形成 12 / 13 两级层级。 */
    val rowLabelSize = 12.sp
    val rowLine = 19.sp
    /** 键值行数值字号：与标签同字号，靠颜色与等宽数字区分主次。 */
    val rowValueSize = 12.sp
    /** 数值颜色透明度。纯黑过重，0.82 保留可读性同时弱于标题。 */
    const val rowValueAlpha = 0.82f
    /** 标签与数值之间的最小间距。 */
    val rowGap = 16.dp
    /**
     * 相邻两行之间的垂直间距。
     *
     * 6dp 是按上面的行高与字号实测的最佳值：行距再小，两行文字会粘成一片；
     * 再大，长面板整体高度会失控。此值不可与行高互相替代。
     */
    val rowSpacing = 7.dp    /** 数值统一使用等宽数字，纵向对比时小数点能对齐。 */
    const val rowValueFeature = "tnum"

    // ── 操作按钮 ────────────────────────────────────────────────────────────
    /**
     * 面板内主操作按钮高度。
     *
     * 比 Material 默认 40dp 矮一档：这是信息面板，按钮太高压过数据本身；
     * 也不宜更矮，低于 28dp 在触屏上容易点不中。
     */
    val actionButtonHeight = 30.dp
    /** 按钮圆角取高度的一半，两端成胶囊形。 */
    val actionButtonCorner = 15.dp

    // ── 组间距 ────────────────────────────��─────────────────────────────
    /**
     * 组与组之间的垂直间距。
     *
     * 取 17dp（而非行间距的 3~4 倍）是因为实测发现：组内每行行高 18sp 已经含
     * 约 3dp 的内部留白，两行之间的**视觉**空白约 33px；组间距若仍是 14dp，
     * 相邻组标题与上一组末行的视觉空白只有 36~55px，与组内差距不明显，
     * 分组节奏出不来。17dp 让组间视觉空白稳定在 52px 左右，比组内大一档。
     */
    val groupSpacing = 15.dp

    // ── 滑块区（自动压缩）────────────────────────────────────────────────
    /**
     * 滑块可交互区域高度。
     *
     * Material 的 Slider 自带 48dp 高（其中大块是给触摸预留的空白），
     * 放进信息卡片里会凭空多吃掉一行半的高度，让「自动压缩」整组显得很空。
     * 收到 32dp：仍满足最小触摸目标（32dp 是手指可可靠命中的下限），
     * 同时拇指与滑轨上下不再拖出大片空白。
     */
    /** 滑杆宽度权重：1.6 对应约 62% 宽，右侧留给区间提示。整宽滑杆像分割线。 */
    const val sliderWeight = 1.6f

    /** 滑杆与右侧区间提示的间距。 */
    val sliderTrailingGap = 6.dp

    val sliderHeight = 34.dp
    /** 滑轨粗细：与顶部进度条一致，避免同一张卡里两种粗细。 */
    val sliderTrackHeight = 6.dp
    /**
     * 滑块与压缩按钮之间的间距。
     *
     * 说明文字删掉后，滑块到按钮之间只剩这一处留白；取 8dp 让按钮紧贴滑杆，
     * 整个「自动压缩」组收成一个紧凑的操作区，而不是被空白拉散。
     */
    val compactButtonGap = 8.dp
}
